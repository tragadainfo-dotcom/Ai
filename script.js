const KEY="claude-island-progress";
let done=[];
try{done=JSON.parse(localStorage.getItem(KEY))||[]}catch(e){}
const root=document.getElementById("levels");
function render(){
  root.innerHTML="";
  LEVELS.forEach(([t,r,items,goal],i)=>{
    const el=document.createElement("article");
    el.className="glass level"+(done.includes(i)?" done":"");
    el.innerHTML=`<div class="num">${i+1}</div><h3>${t}</h3><div class="range">Уроки ${r}</div>
      <ul>${items.map(x=>`<li>${x}</li>`).join("")}</ul>
      <p class="goal"><b>Цель:</b> ${goal}</p>
      <button type="button">${done.includes(i)?"Пройдено ✓":"Отметить пройденным"}</button>`;
    el.querySelector("button").onclick=()=>{
      done=done.includes(i)?done.filter(n=>n!==i):[...done,i];
      try{localStorage.setItem(KEY,JSON.stringify(done))}catch(e){}
      render();
    };
    root.appendChild(el);
  });
  document.getElementById("navProgress").textContent=`${done.length} из 10`;
  document.getElementById("heroBar").style.width=done.length*10+"%";
}
render();
